def _summary(terrain: dict, source_name: str) -> dict:
    cover = _land_cover(terrain)
    total = int(cover.size)
    water = int(np.count_nonzero(cover == 5))
    road = int(np.count_nonzero(cover == 0))
    obstacle_count = int(np.count_nonzero(np.asarray(terrain.get("obstacle_type", np.zeros_like(cover))) != 0))
    summary = {
        "source": source_name,
        "grid": f"{cover.shape[1]} x {cover.shape[0]}",
        "total cells": total,
        "water cells": f"{water} ({100.0 * water / total:.2f}%)",
        "road cells": f"{road} ({100.0 * road / total:.2f}%)",
        "obstacle cells": f"{obstacle_count} ({100.0 * obstacle_count / total:.2f}%)",
        "fuel source": terrain.get("fuel_source", "unknown"),
        "DEM resolution": terrain.get("dem_resolution_m", "unknown"),
        "CRS": terrain.get("projected_crs", "unknown"),
    }
    if "bbox" in terrain:
        bbox = np.asarray(terrain["bbox"]).reshape(-1)
        if len(bbox) == 4:
            summary["bbox"] = ", ".join(f"{float(v):.5f}" for v in bbox)
    metadata = terrain.get("metadata", {})
    source_description = metadata.get("source_description") or terrain.get("source")
    if source_description:
        summary["description"] = source_description
    if terrain.get("_frames"):
        metrics = _search_difficulty_metrics(terrain)
        summary["searchable area"] = f"{100.0 * metrics['searchable_fraction']:.2f}%"
        summary["expected drone lanes"] = metrics["lane_count"]
        summary["spawn feasible cells"] = (
            f"{metrics['spawn_feasible_cells']} "
            f"({100.0 * metrics['spawn_feasible_fraction']:.2f}%)"
        )
        summary["traversable components"] = metrics["component_count"]
    return summary


def _search_difficulty_metrics(terrain: dict) -> dict:
    cover = _land_cover(terrain)
    total = max(int(cover.size), 1)
    searchable = _searchable_mask(terrain)
    spawn_feasible = _spawn_feasible_mask(terrain)
    traversable = _traversable_mask(terrain)
    _, component_sizes = _connected_components(traversable)
    lanes, _ = _expected_lawnmower_lanes(terrain)
    n_drones = max(int(terrain.get("_n_drones", 0)), 1)
    n_survivors = max(int(terrain.get("_n_survivors", 0)), 1)
    largest = max(component_sizes) if component_sizes else 0
    return {
        "searchable_fraction": float(searchable.mean()),
        "spawn_feasible_fraction": float(spawn_feasible.mean()),
        "traversable_fraction": float(traversable.mean()),
        "largest_component_fraction": float(largest / total),
        "component_count": len(component_sizes),
        "lane_count": len(lanes),
        "lanes_per_drone": float(len(lanes) / n_drones),
        "spawn_feasible_cells": int(spawn_feasible.sum()),
        "feasible_per_survivor": float(spawn_feasible.sum() / n_survivors),
    }


def _searchable_mask(terrain: dict) -> np.ndarray:
    cover = _land_cover(terrain)
    return (cover != 5) & (cover != 4)


def _spawn_feasible_mask(terrain: dict) -> np.ndarray:
    if "traversable" in terrain:
        return np.asarray(terrain["traversable"], dtype=bool)
    cover = _land_cover(terrain)
    obstacle = np.asarray(terrain.get("obstacle_type", np.zeros_like(cover)), dtype=int)
    return _searchable_mask(terrain) & (obstacle == 0)


def _traversable_mask(terrain: dict) -> np.ndarray:
    if "traversable" in terrain:
        return np.asarray(terrain["traversable"], dtype=bool)
    return _spawn_feasible_mask(terrain)


def _initial_frame(terrain: dict) -> dict:
    frames = terrain.get("_frames") or []
    return frames[0] if frames else {}


def _world_points_to_grid(terrain: dict, points: list[tuple[float, float]]) -> tuple[list[float], list[float]]:
    cover = _land_cover(terrain)
    height, width = cover.shape
    world = terrain.get("_world", {})
    x_semidim = float(world.get("x_semidim", 1.0))
    y_semidim = float(world.get("y_semidim", 1.0))
    xs = []
    ys = []
    for x, y in points:
        gx = (float(x) + x_semidim) / (2.0 * x_semidim) * width
        gy = (float(y) + y_semidim) / (2.0 * y_semidim) * height
        xs.append(round(min(max(gx, 0.0), width - 1.0), 3))
        ys.append(round(min(max(gy, 0.0), height - 1.0), 3))
    return xs, ys


def _expected_lawnmower_lanes(terrain: dict) -> tuple[list[dict], dict]:
    cover = _land_cover(terrain)
    size_y, size_x = cover.shape
    mission = terrain.get("_mission", {})
    world = terrain.get("_world", {})
    x_semidim = float(world.get("x_semidim", 1.0))
    y_semidim = float(world.get("y_semidim", 1.0))
    agent_radius = float(terrain.get("_agent_radius", 0.04))
    flight_levels = mission.get("terrain", {}).get("drone_flight_levels", [])
    fov_deg = float(mission.get("terrain", {}).get("drone_camera_fov_deg", 65.0))
    min_altitude = min(float(v) for v in flight_levels) if flight_levels else 0.18
    footprint = max(min_altitude * math.tan(math.radians(fov_deg) / 2.0), 1e-6)
    lane_spacing = footprint * DRONE_LANE_SPACING_FACTOR

    margin = max(agent_radius, 0.02)
    x_min_world = -x_semidim + margin
    x_max_world = x_semidim - margin
    y_min_world = -y_semidim + margin
    y_max_world = y_semidim - margin
    span_y = max(y_max_world - y_min_world, 1e-6)
    candidate_lane_count = max(1, int(math.ceil(span_y / lane_spacing)) + 1)
    lane_ys = np.linspace(y_min_world, y_max_world, candidate_lane_count)

    cell_w = 2.0 * x_semidim / size_x
    cell_h = 2.0 * y_semidim / size_y
    cell_xs = np.linspace(-x_semidim + 0.5 * cell_w, x_semidim - 0.5 * cell_w, size_x)
    cell_ys = np.linspace(-y_semidim + 0.5 * cell_h, y_semidim - 0.5 * cell_h, size_y)
    searchable = _searchable_mask(terrain)

    lanes: list[dict] = []
    for lane_y in lane_ys:
        y_mask = np.abs(cell_ys - lane_y) <= lane_spacing * 0.5
        lane_mask = searchable & y_mask.reshape(size_y, 1)
        weight = int(lane_mask.sum())
        if weight <= 0:
            continue
        x_used = lane_mask.any(axis=0)
        used_indices = np.flatnonzero(x_used)
        segment_margin = max(0.5 * footprint, 0.5 * cell_w)
        lanes.append({
            "y": float(lane_y),
            "x_min": max(x_min_world, float(cell_xs[int(used_indices.min())]) - segment_margin),
            "x_max": min(x_max_world, float(cell_xs[int(used_indices.max())]) + segment_margin),
            "weight": float(weight),
        })
    if not lanes:
        lanes = [
            {"y": float(y), "x_min": x_min_world, "x_max": x_max_world, "weight": 1.0}
            for y in lane_ys
        ]
    return lanes, {
        "footprint": footprint,
        "lane_spacing": lane_spacing,
        "candidate_lane_count": candidate_lane_count,
    }


def _balanced_lane_blocks(lanes: list[dict], n_drones: int) -> list[list[dict]]:
    n_drones = max(int(n_drones), 1)
    blocks: list[list[dict]] = []
    start = 0
    remaining_weight = sum(float(lane["weight"]) for lane in lanes)
    for drone_idx in range(n_drones):
        remaining_drones = n_drones - drone_idx
        if start >= len(lanes):
            blocks.append([])
            continue
        if remaining_drones == 1:
            blocks.append(lanes[start:])
            break
        target = remaining_weight / remaining_drones
        end = start
        acc = 0.0
        max_end = len(lanes) - (remaining_drones - 1)
        while end < max_end:
            next_acc = acc + float(lanes[end]["weight"])
            if acc > 0 and abs(next_acc - target) > abs(acc - target):
                break
            acc = next_acc
            end += 1
            if acc >= target:
                break
        if end == start:
            acc = float(lanes[end]["weight"])
            end += 1
        blocks.append(lanes[start:end])
        remaining_weight -= acc
        start = end
    while len(blocks) < n_drones:
        blocks.append([])
    return blocks


def _connected_components(mask: np.ndarray) -> tuple[np.ndarray, list[int]]:
    mask = np.asarray(mask, dtype=bool)
    labels = np.full(mask.shape, -1, dtype=int)
    sizes: list[int] = []
    component = 0
    height, width = mask.shape
    for y in range(height):
        for x in range(width):
            if not mask[y, x] or labels[y, x] >= 0:
                continue
            stack = [(x, y)]
            labels[y, x] = component
            size = 0
            while stack:
                cx, cy = stack.pop()
                size += 1
                for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                    if 0 <= nx < width and 0 <= ny < height and mask[ny, nx] and labels[ny, nx] < 0:
                        labels[ny, nx] = component
                        stack.append((nx, ny))
            sizes.append(size)
            component += 1
    return labels, sizes


