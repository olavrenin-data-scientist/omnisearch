def _plot_obstacle_by_land_cover(terrain: dict) -> dict:
    if "obstacle_type" not in terrain:
        return _empty_plot("obstacle-by-cover", "Obstacle by Land Cover", "No obstacle_type grid found.")
    cover = _land_cover(terrain)
    obstacle = np.asarray(terrain["obstacle_type"], dtype=int)
    matrix = np.zeros((len(OBSTACLE_NAMES), len(LAND_COVER_NAMES)), dtype=int)
    for oi in range(len(OBSTACLE_NAMES)):
        for ci in range(len(LAND_COVER_NAMES)):
            matrix[oi, ci] = int(np.count_nonzero((obstacle == oi) & (cover == ci)))
    trace = {
        "type": "heatmap",
        "x": LAND_COVER_NAMES,
        "y": OBSTACLE_NAMES,
        "z": matrix.tolist(),
        "colorscale": "Blues",
        "colorbar": {"title": "cells"},
        "hovertemplate": "%{y} on %{x}<br>cells=%{z}<extra></extra>",
    }
    return _plot(
        "obstacle-by-cover",
        "Obstacle Cells by Land-Cover Class",
        [trace],
        {},
        "Cross-tab of object placement against land cover. This catches houses in forests/water and trees on roads.",
    )


def _plot_land_cover_adjacency(terrain: dict) -> dict:
    cover = _land_cover(terrain)
    matrix = np.zeros((len(LAND_COVER_NAMES), len(LAND_COVER_NAMES)), dtype=int)
    pairs = [
        (cover[:, :-1], cover[:, 1:]),
        (cover[:-1, :], cover[1:, :]),
    ]
    for left, right in pairs:
        for a, b in zip(left.reshape(-1), right.reshape(-1)):
            ai = int(a)
            bi = int(b)
            if 0 <= ai < len(LAND_COVER_NAMES) and 0 <= bi < len(LAND_COVER_NAMES) and ai != bi:
                matrix[ai, bi] += 1
                matrix[bi, ai] += 1
    trace = {
        "type": "heatmap",
        "x": LAND_COVER_NAMES,
        "y": LAND_COVER_NAMES,
        "z": matrix.tolist(),
        "colorscale": "Magma",
        "colorbar": {"title": "neighbor boundaries"},
        "hovertemplate": "%{y} next to %{x}<br>boundaries=%{z}<extra></extra>",
    }
    return _plot(
        "land-cover-adjacency",
        "Land-Cover Boundary / Adjacency Matrix",
        [trace],
        {},
        "Counts neighboring cells of different classes. Very high boundary counts can indicate noisy, fragmented terrain.",
    )


