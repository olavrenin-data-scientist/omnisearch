"""Generate a Plotly.js EDA report for an OmniSearch terrain cache.

Examples:

    python scripts/terrain_eda.py \
      --terrain-cache data/terrain_cache/malibu_128.npz

    python scripts/terrain_eda.py \
      --trajectory web/trajectories/nearest_candidate.json \
      --out results/eda/nearest_candidate_terrain_eda.html
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Iterable

import numpy as np


ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


PLOTLY_JS = "https://cdn.plot.ly/plotly-2.35.2.min.js"
LAND_COVER_NAMES = ["road", "open", "brush", "forest", "rock", "water"]
LAND_COVER_COLORS = ["#b59665", "#47783d", "#315a2e", "#203d24", "#555963", "#2563eb"]
OBSTACLE_NAMES = ["none", "tree", "house"]
OBSTACLE_COLORS = ["#111827", "#1d5128", "#a34d3d"]
CONTINUOUS_LAYERS = ("elevation", "slope", "moisture", "fuel_density", "rockiness")
# The planner's footprint value is camera radius, so 1.6 * radius = 0.8 * full footprint width.
DRONE_LANE_SPACING_FACTOR = 1.6


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--terrain-cache",
        default=str(ROOT / "data" / "terrain_cache" / "malibu_128.npz"),
        help="Terrain .npz cache generated by scripts/build_real_terrain_cache.py.",
    )
    p.add_argument(
        "--trajectory",
        default=None,
        help="Optional trajectory JSON. If provided, uses metadata.terrain and includes movement layers.",
    )
    p.add_argument("--out", default=None, help="Output HTML path.")
    p.add_argument("--sample-points", type=int, default=8_000, help="Max samples per box/scatter plot.")
    args = p.parse_args()

    if args.trajectory:
        terrain, source_name = _load_from_trajectory(Path(args.trajectory))
        default_stem = Path(args.trajectory).stem
    else:
        terrain, source_name = _load_from_cache(Path(args.terrain_cache))
        default_stem = Path(args.terrain_cache).stem

    out = Path(args.out) if args.out else ROOT / "results" / "eda" / f"{default_stem}_terrain_eda.html"
    generate_terrain_eda_html(
        terrain=terrain,
        source_name=source_name,
        out=out,
        sample_points=args.sample_points,
    )


def generate_terrain_eda_html(
    *,
    terrain: dict,
    source_name: str,
    out: Path,
    sample_points: int = 8_000,
) -> Path:
    _validate_terrain(terrain)
    plots = [
        _plot_land_cover_distribution(terrain),
        _plot_spatial_land_cover(terrain),
        _plot_spatial_continuous_layers(terrain),
        _plot_continuous_distributions(terrain, sample_points),
        _plot_class_conditional_layers(terrain, sample_points),
        _plot_correlation_matrix(terrain),
        _plot_obstacle_distribution(terrain),
        _plot_obstacle_by_land_cover(terrain),
        _plot_land_cover_adjacency(terrain),
    ]
    if "movement_cost" in terrain:
        plots.append(_plot_movement_cost_heatmap(terrain))
    if "speed_multiplier" in terrain:
        plots.append(_plot_speed_multiplier_heatmap(terrain))
    if "movement_cost" in terrain or "speed_multiplier" in terrain or "traversable" in terrain:
        plots.append(_plot_mobility_diagnostics(terrain, sample_points))
    if terrain.get("_frames"):
        plots.extend([
            _plot_search_difficulty_summary(terrain),
            _plot_expected_drone_lanes(terrain),
            _plot_spawn_feasibility_map(terrain),
            _plot_ugv_survivor_distances(terrain),
            _plot_traversable_components(terrain),
        ])

    summary = _summary(terrain, source_name)
    html = _build_html(summary=summary, plots=plots)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html)
    print(f"Wrote {out}")
    print(f"Open with: open {out}")
    return out


def _load_from_cache(path: Path) -> tuple[dict, str]:
    if not path.exists():
        raise SystemExit(f"terrain cache not found: {path}")
    with np.load(path, allow_pickle=False) as data:
        terrain = {}
        for name in (
            "land_cover",
            "elevation",
            "slope",
            "moisture",
            "fuel_density",
            "rockiness",
            "obstacle_type",
            "obstacle_height",
            "bbox",
        ):
            if name in data:
                terrain[name] = np.asarray(data[name])
        terrain["source"] = _scalar(data, "source", str(path))
        terrain["fuel_source"] = _scalar(data, "fuel_source", "unknown")
        terrain["dem_resolution_m"] = _scalar(data, "dem_resolution_m", "unknown")
        terrain["projected_crs"] = _scalar(data, "projected_crs", "unknown")
        if "metadata_json" in data:
            try:
                terrain["metadata"] = json.loads(str(data["metadata_json"].item()))
            except (ValueError, TypeError):
                terrain["metadata"] = {}
    return terrain, str(path)


def _load_from_trajectory(path: Path) -> tuple[dict, str]:
    if not path.exists():
        raise SystemExit(f"trajectory not found: {path}")
    payload = json.loads(path.read_text())
    meta = payload.get("metadata", {})
    terrain_meta = meta.get("terrain", {})
    if not terrain_meta:
        raise SystemExit("trajectory metadata does not contain terrain arrays")
    terrain = {
        "source": terrain_meta.get("source_description") or terrain_meta.get("source") or str(path),
        "metadata": terrain_meta.get("source_metadata", {}),
        "_frames": payload.get("frames", []),
        "_mission": meta,
        "_world": meta.get("world", {}),
        "_n_drones": int(meta.get("n_drones", 0)),
        "_n_ground": int(meta.get("n_ground", 0)),
        "_n_survivors": int(meta.get("n_survivors", 0)),
        "_agent_radius": float(meta.get("agent_radius", 0.04)),
    }
    for name in (
        "land_cover",
        "elevation",
        "slope",
        "moisture",
        "fuel_density",
        "rockiness",
        "obstacle_type",
        "obstacle_height",
        "movement_cost",
        "speed_multiplier",
        "traversable",
        "required_clearance",
        "required_clearance_msl",
    ):
        if name in terrain_meta:
            terrain[name] = np.asarray(terrain_meta[name])
    return terrain, str(path)


def _validate_terrain(terrain: dict) -> None:
    if "land_cover" not in terrain:
        raise SystemExit("terrain is missing land_cover")
    shape = np.asarray(terrain["land_cover"]).shape
    if len(shape) != 2:
        raise SystemExit("land_cover must be a 2D grid")
    for name in CONTINUOUS_LAYERS:
        if name not in terrain:
            raise SystemExit(f"terrain is missing {name}")
        if np.asarray(terrain[name]).shape != shape:
            raise SystemExit(f"{name} shape does not match land_cover")


