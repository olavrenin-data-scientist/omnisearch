def _plot_mobility_diagnostics(terrain: dict, sample_points: int) -> dict:
    cover = _land_cover(terrain)
    traces = []
    if "movement_cost" in terrain:
        cost = _finite(terrain["movement_cost"])
        x = []
        y = []
        for cover_id, cover_name in enumerate(LAND_COVER_NAMES):
            sampled = _sample(cost[cover == cover_id], max(sample_points // len(LAND_COVER_NAMES), 1))
            x.extend([cover_name] * len(sampled))
            y.extend(_round_list(sampled))
        traces.append({
            "type": "box",
            "name": "movement cost",
            "x": x,
            "y": y,
            "boxpoints": "outliers",
            "marker": {"color": "#60a5fa"},
        })
    if "speed_multiplier" in terrain:
        speed = _finite(terrain["speed_multiplier"])
        x = []
        y = []
        for cover_id, cover_name in enumerate(LAND_COVER_NAMES):
            sampled = _sample(speed[cover == cover_id], max(sample_points // len(LAND_COVER_NAMES), 1))
            x.extend([cover_name] * len(sampled))
            y.extend(_round_list(sampled))
        traces.append({
            "type": "box",
            "name": "speed multiplier",
            "x": x,
            "y": y,
            "boxpoints": "outliers",
            "marker": {"color": "#22c55e"},
        })
    if "traversable" in terrain:
        traversable = np.asarray(terrain["traversable"], dtype=bool)
        labels = []
        pct = []
        for cover_id, cover_name in enumerate(LAND_COVER_NAMES):
            mask = cover == cover_id
            labels.append(cover_name)
            pct.append(round(float(100.0 * traversable[mask].mean()) if np.any(mask) else 0.0, 4))
        traces.append({
            "type": "scatter",
            "mode": "lines+markers",
            "name": "traversable %",
            "x": labels,
            "y": pct,
            "yaxis": "y2",
            "line": {"color": "#fbbf24", "width": 3},
        })
    return _plot(
        "mobility-diagnostics",
        "Ground Mobility Diagnostics by Land Cover",
        traces,
        {
            "xaxis": {"title": "land-cover class"},
            "yaxis": {"title": "movement cost / speed multiplier"},
            "yaxis2": {"title": "traversable (%)", "overlaying": "y", "side": "right", "range": [0, 100]},
            "legend": {"orientation": "h"},
        },
        "Available when the input is a trajectory JSON, because movement/traversability are scenario-derived layers.",
    )


