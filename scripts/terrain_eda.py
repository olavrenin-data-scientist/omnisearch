def _class_counts(values: np.ndarray, names: list[str]) -> tuple[list[str], list[int], list[float]]:
    total = max(int(values.size), 1)
    labels = []
    counts = []
    pct = []
    for idx, name in enumerate(names):
        count = int(np.count_nonzero(values == idx))
        labels.append(name)
        counts.append(count)
        pct.append(round(float(100.0 * count / total), 4))
    return labels, counts, pct


def _discrete_colorscale(colors: list[str]) -> list[list[float | str]]:
    max_value = len(colors) - 1
    stops: list[list[float | str]] = []
    for idx, color in enumerate(colors):
        lo = max(0.0, (idx - 0.5) / max_value)
        hi = min(1.0, (idx + 0.5) / max_value)
        stops.append([lo, color])
        stops.append([hi, color])
    return stops


def _finite(array: np.ndarray) -> np.ndarray:
    array = np.asarray(array, dtype=float)
    fill = float(np.nanmean(array)) if np.isfinite(array).any() else 0.0
    return np.nan_to_num(array, nan=fill, posinf=fill, neginf=fill)


def _sample(values: np.ndarray, max_points: int) -> np.ndarray:
    values = np.asarray(values, dtype=float).reshape(-1)
    values = values[np.isfinite(values)]
    if max_points <= 0 or len(values) <= max_points:
        return values
    idx = np.linspace(0, len(values) - 1, max_points, dtype=int)
    return values[idx]


def _round_grid(array: np.ndarray) -> list[list[float]]:
    return [[round(float(value), 4) for value in row] for row in np.asarray(array).tolist()]


def _round_list(values: Iterable[float]) -> list[float]:
    out = []
    for value in values:
        value = float(value)
        if math.isfinite(value):
            out.append(round(value, 4))
    return out


def _scalar(data, key: str, default):
    if key not in data:
        return default
    value = data[key]
    try:
        return value.item()
    except ValueError:
        return value.tolist()


def _escape_html(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


