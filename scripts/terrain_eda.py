def _plot_continuous_distributions(terrain: dict, sample_points: int) -> dict:
    cover = _land_cover(terrain)
    land_mask = cover != 5
    traces = []
    for i, name in enumerate(CONTINUOUS_LAYERS):
        values = _sample(_finite(terrain[name])[land_mask], sample_points)
        traces.append({
            "type": "histogram",
            "name": name,
            "x": _round_list(values),
            "opacity": 0.68,
            "nbinsx": 45,
            "marker": {"color": LAND_COVER_COLORS[(i + 1) % len(LAND_COVER_COLORS)]},
        })
    return _plot(
        "continuous-distributions",
        "Continuous Terrain-Layer Distributions",
        traces,
        {
            "barmode": "overlay",
            "xaxis": {"title": "normalized layer value"},
            "yaxis": {"title": "cell count"},
        },
        "Histograms are sampled from non-water cells when water exists, because water can dominate moisture/fuel statistics.",
    )


def _plot_class_conditional_layers(terrain: dict, sample_points: int) -> dict:
    cover = _land_cover(terrain)
    traces = []
    for i, name in enumerate(CONTINUOUS_LAYERS):
        x = []
        y = []
        values = _finite(terrain[name])
        for cover_id, cover_name in enumerate(LAND_COVER_NAMES):
            mask = cover == cover_id
            sampled = _sample(values[mask], max(sample_points // len(CONTINUOUS_LAYERS), 1))
            x.extend([cover_name] * len(sampled))
            y.extend(_round_list(sampled))
        traces.append({
            "type": "box",
            "name": name,
            "x": x,
            "y": y,
            "boxpoints": "outliers",
            "marker": {"color": LAND_COVER_COLORS[i % len(LAND_COVER_COLORS)]},
        })
    return _plot(
        "class-conditional-layers",
        "Terrain Layers by Land-Cover Class",
        traces,
        {
            "xaxis": {"title": "land-cover class"},
            "yaxis": {"title": "layer value"},
            "boxmode": "group",
        },
        "Checks whether the class semantics line up with the continuous fields, for example forest/brush having higher fuel.",
    )


def _plot_correlation_matrix(terrain: dict) -> dict:
    layers = [name for name in CONTINUOUS_LAYERS if name in terrain]
    for optional in ("movement_cost", "speed_multiplier"):
        if optional in terrain:
            layers.append(optional)
    arrays = []
    for name in layers:
        arrays.append(_finite(terrain[name]).reshape(-1))
    corr = np.corrcoef(np.asarray(arrays))
    trace = {
        "type": "heatmap",
        "x": layers,
        "y": layers,
        "z": _round_grid(corr),
        "zmin": -1,
        "zmax": 1,
        "colorscale": "RdBu",
        "reversescale": True,
        "colorbar": {"title": "corr"},
        "text": _round_grid(corr),
        "hovertemplate": "%{y} vs %{x}<br>corr=%{z:.3f}<extra></extra>",
    }
    return _plot(
        "terrain-correlations",
        "Terrain Layer Correlation Matrix",
        [trace],
        {"xaxis": {"side": "bottom"}, "yaxis": {"autorange": "reversed"}},
        "Useful for spotting accidental coupling, for example fuel_density tracking elevation too strongly.",
    )


